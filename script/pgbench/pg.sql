CREATE EXTENSION IF NOT EXISTS postgis;
CREATE TABLE tb_shop (
  id bigint PRIMARY KEY, name text NOT NULL, type_id bigint NOT NULL,
  images text NOT NULL, area text, address text NOT NULL, x double precision NOT NULL, y double precision NOT NULL,
  avg_price bigint, sold bigint NOT NULL, comments bigint NOT NULL, score integer NOT NULL,
  open_hours text, create_time timestamptz, update_time timestamptz,
  location geography(Point,4326) GENERATED ALWAYS AS
    (ST_SetSRID(ST_MakePoint(x,y),4326)::geography) STORED
);
CREATE INDEX shop_type ON tb_shop(type_id);
CREATE TABLE tb_user (id bigint PRIMARY KEY,phone varchar(11) UNIQUE,password text,nick_name text,icon text,
  create_time timestamptz NOT NULL,update_time timestamptz NOT NULL);
CREATE TABLE tb_blog (id bigint PRIMARY KEY,shop_id bigint NOT NULL,user_id bigint NOT NULL,title text NOT NULL,
  images text NOT NULL,content text NOT NULL,liked bigint,comments bigint,
  create_time timestamptz NOT NULL,update_time timestamptz NOT NULL,like_version bigint NOT NULL DEFAULT 0);
CREATE TABLE bench_slot(id bigint PRIMARY KEY, remaining integer NOT NULL);
CREATE TABLE bench_receipt(order_id bigint PRIMARY KEY,created_at timestamptz DEFAULT CURRENT_TIMESTAMP);
CREATE TABLE bench_order(id bigint PRIMARY KEY,user_id bigint NOT NULL,voucher_id bigint NOT NULL,status integer NOT NULL,created_at timestamptz DEFAULT CURRENT_TIMESTAMP,UNIQUE(user_id,voucher_id));
CREATE INDEX bench_expiry ON bench_order(status,created_at,id);
CREATE TABLE bench_notice(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,event_key varchar(128) NOT NULL UNIQUE,user_id bigint NOT NULL,content varchar(255),pushed boolean DEFAULT FALSE,created_at timestamptz DEFAULT CURRENT_TIMESTAMP);
CREATE INDEX bench_inbox ON bench_notice(user_id,id);
CREATE INDEX bench_dispatch ON bench_notice(pushed,id);
