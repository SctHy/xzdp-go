CREATE TABLE shop_geo_dirty(shop_id bigint PRIMARY KEY);
CREATE FUNCTION mark_shop_geo_dirty() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'DELETE' THEN
        INSERT INTO shop_geo_dirty VALUES(OLD.id) ON CONFLICT DO NOTHING;
    ELSIF TG_OP = 'INSERT' OR (OLD.type_id,OLD.x,OLD.y) IS DISTINCT FROM (NEW.type_id,NEW.x,NEW.y) THEN
        INSERT INTO shop_geo_dirty VALUES(NEW.id) ON CONFLICT DO NOTHING;
    END IF;
    RETURN NULL;
END $$;
CREATE TRIGGER track_shop_geo AFTER INSERT OR UPDATE OR DELETE ON tb_shop FOR EACH ROW EXECUTE FUNCTION mark_shop_geo_dirty();
