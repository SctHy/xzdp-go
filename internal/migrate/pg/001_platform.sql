CREATE FUNCTION touch_updated_at() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.update_time IS NOT DISTINCT FROM OLD.update_time THEN
        NEW.update_time := statement_timestamp();
    END IF;
    RETURN NEW;
END $$;

